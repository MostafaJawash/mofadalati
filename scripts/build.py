def fixdigits(s):
    return re.sub(r'\d[\d./]*', lambda m: m.group(0)[::-1], s)


def norm(s):
    if s is None:
        return None
    lines = [l[::-1].strip() for l in s.split('\n')]
    lines = [l for l in lines if l not in ('ى', 'ي', '')]
    t = ' '.join(lines)
    t = fixdigits(t)
    if re.fullmatch(r'[ـ\s]*', t):
        return 'ـ' if t.strip() else ''
    t = t.replace('ـ', '')
    for a, b in FIX:
        t = re.sub(a[3:], b, t) if a.startswith('re:') else t.replace(a, b)
    t = re.sub(r'%(\d+)', r'\1%', t).replace('٪', '%')
    return re.sub(r'\s+', ' ', t).strip()


rows = []
for pi in range(20):
    page = doc[pi]
    for t in page.find_tables().tables:
        data = t.extract()
        ncol = len(data[0])
        colx = [None] * ncol
        for r in t.rows:
            for j, c in enumerate(r.cells):
                if c is not None and (colx[j] is None or c[2] - c[0] < colx[j][1] - colx[j][0]):
                    colx[j] = (c[0], c[2])
        prev = None
        for r, vals in zip(t.rows, data):
            cells = r.cells
            filled = []
            for j in range(ncol):
                v = vals[j]
                if v is None:
                    cx = (colx[j][0] + colx[j][1]) / 2
                    hcov = any(c is not None and k != j and c[0] < cx < c[2] and c[1] <= r.bbox[1] + 1
                               for k, c in enumerate(cells))
                    v = '<<H>>' if hcov else (prev[j] if prev else None)
                filled.append(v)
            prev = filled
            if ncol == 10:
                _, _, _, _, pc, pm, gc, gm, city, name = filled
            elif ncol == 8:
                _, _, _, _, pc, gc, city, name = filled
                pm = gm = '<<H>>'
            else:
                continue
            nm = norm(name)
            if not nm or 'اسم الكلية' in nm or nm.startswith('مفاضلة') or ('الحد' in nm and 'الدرجات' in nm):
                continue
            h = lambda x: None if x == '<<H>>' else norm(x)
            rows.append(dict(page=pi + 1, name=nm, city=norm(city), gm=h(gm), gc=h(gc), pm=h(pm), pc=h(pc)))

json.dump(rows, open("rows.json", "w", encoding="utf-8"), ensure_ascii=False, indent=0)
print(len(rows))
